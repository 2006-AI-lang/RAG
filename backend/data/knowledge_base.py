def get_categories():
    """获取分类统计（所有知识）。"""
    from collections import Counter
    items = get_all_knowledge(user_id=None)  # 获取所有动态条目用于分类统计
    cats = Counter(item["category"] for item in items)
    return [{"category": k, "count": v} for k, v in cats.items()]


